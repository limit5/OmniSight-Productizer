def test_three_parallel_lesson_files_merge_without_conflict(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    subprocess.run(["git", "init", "-q", "-b", "main"], cwd=repo, check=True)
    subprocess.run(["git", "config", "user.email", "test@example.invalid"], cwd=repo, check=True)
    subprocess.run(["git", "config", "user.name", "Test User"], cwd=repo, check=True)
    (repo / "docs/sop/lessons").mkdir(parents=True)
    (repo / "docs/sop/lessons/.gitkeep").write_text("", encoding="utf-8")
    subprocess.run(["git", "add", "."], cwd=repo, check=True)
    subprocess.run(["git", "commit", "-q", "-m", "base"], cwd=repo, check=True)

    for ticket in ("OP-801", "OP-802", "OP-803"):
        subprocess.run(["git", "switch", "-q", "-c", ticket, "main"], cwd=repo, check=True)
        path = repo / "docs/sop/lessons" / f"L-{ticket}-parallel.md"
        path.write_text(f"lesson for {ticket}\n", encoding="utf-8")
        subprocess.run(["git", "add", str(path.relative_to(repo))], cwd=repo, check=True)
        subprocess.run(["git", "commit", "-q", "-m", ticket], cwd=repo, check=True)

    subprocess.run(["git", "switch", "-q", "main"], cwd=repo, check=True)
    for ticket in ("OP-801", "OP-802", "OP-803"):
        subprocess.run(["git", "merge", "--no-ff", "--no-edit", ticket], cwd=repo, check=True)

    merged = sorted(path.name for path in (repo / "docs/sop/lessons").glob("L-OP-*.md"))
    assert merged == [
        "L-OP-801-parallel.md",
        "L-OP-802-parallel.md",
        "L-OP-803-parallel.md",
    ]
